import puppeteer from 'puppeteer-core'; import chromium from '@sparticuz/chromium';
const [url,out]=process.argv.slice(2);
const b=await puppeteer.launch({executablePath:await chromium.executablePath(),args:chromium.args,headless:true});
const p=await b.newPage(); await p.setViewport({width:1440,height:900});
await p.goto(url,{waitUntil:'networkidle0'});
await p.evaluate(()=>document.querySelectorAll('img[loading=lazy]').forEach(i=>i.loading='eager'));
const el=await p.$('.pt-related'); await el.scrollIntoView(); await new Promise(r=>setTimeout(r,800));
const c=await p.$('.pt-rcard'); await c.hover(); await new Promise(r=>setTimeout(r,600));
await p.addStyleTag({content:'.pt-header{display:none!important}'});
await el.screenshot({path:out}); console.log('ok'); await b.close();
